import { ethers, network, artifacts } from "hardhat";
import fs from "node:fs";
import path from "node:path";

const WEB_CONTRACTS_DIR = path.resolve(__dirname, "../../web/src/contracts");

async function main() {
  const ballot = await ethers.deployContract("SealedBallot");
  await ballot.waitForDeployment();
  const address = await ballot.getAddress();
  const chainId = Number((await ethers.provider.getNetwork()).chainId);
  const blockNumber = await ethers.provider.getBlockNumber();

  console.log(`SealedBallot deployed to ${address} on ${network.name} (chainId ${chainId})`);

  const artifact = await artifacts.readArtifact("SealedBallot");
  fs.mkdirSync(WEB_CONTRACTS_DIR, { recursive: true });
  fs.writeFileSync(
    path.join(WEB_CONTRACTS_DIR, "abi.ts"),
    `// Generated by contracts/scripts/deploy.ts — do not edit by hand.\nexport const sealedBallotAbi = ${JSON.stringify(
      artifact.abi,
      null,
      2,
    )} as const;\n`,
  );

  const deploymentsPath = path.join(WEB_CONTRACTS_DIR, "deployments.json");
  const deployments = fs.existsSync(deploymentsPath) ? JSON.parse(fs.readFileSync(deploymentsPath, "utf8")) : {};
  deployments[chainId] = { address, deployBlock: blockNumber, network: network.name };
  fs.writeFileSync(deploymentsPath, JSON.stringify(deployments, null, 2) + "\n");

  console.log(`Wrote ABI and address to ${path.relative(process.cwd(), WEB_CONTRACTS_DIR)}`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
